# To write a program in a file and execute it in script mode to find the area and the circumference of a circle.

radius = 7
area = 3.14159 * radius ** 2
circumference = 2 * 3.14159 * radius
print("Radius        :", radius)
print("Area          :", round(area, 2))
print("Circumference :", round(circumference, 2))