# Practical 4 : Dynamic Typing and Variable Assignment
# Informatics Practices (065) - Class XI
# To show that a variable in Python can refer to values of different data types at different times.

value = 25
print(value, type(value))
value = 25.75
print(value, type(value))
value = "Informatics"
print(value, type(value))
value = True
print(value, type(value))
value = [10, 20]
print(value, type(value))